#include <stdio.h>

int main() 
{
    // Integer data type stores whole numbers
    int myNum = 5;

    // Float data type stores decimal numbers
    float myFloatNum = 5.99;

    // Character data type stores a single character
    char myLetter = 'D';

    // Printing values
    printf("%d\n", myNum);
    printf("%f\n", myFloatNum);
    printf("%c\n", myLetter);

    return 0;
}