#include <stdio.h>
#include <math.h>


int main()
{

    // Square Root

    printf("Square root of 16: %.2f\n", sqrt(16));



    // Round a Number

    printf("Ceil of 4.4: %.2f\n", ceil(4.4));

    printf("Floor of 4.7: %.2f\n", floor(4.7));



    // Power

    printf("4 raised to the power 3: %.2f\n", pow(4, 3));



    return 0;
}



/*
Output:

Square root of 16: 4.00
Ceil of 4.4: 5.00
Floor of 4.7: 4.00
4 raised to the power 3: 64.00

*/