#include <stdio.h>

int main() {

    // Good variable name
    int minutesPerHour = 60;

    printf("%d\n", minutesPerHour);


    // Short variable name
    int m = 60;

    printf("%d\n", m);


    // Variable names can contain letters, digits and underscores
    int total_score = 100;

    printf("%d\n", total_score);


    return 0;
}